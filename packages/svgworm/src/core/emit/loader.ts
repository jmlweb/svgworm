/**
 * The loader of `crossOrigin: "inject"` (ADR-0027). It fetches the sprite with CORS and the
 * integrity baked in, parses it inertly, keeps only what an icon sprite needs, and injects it
 * once at the start of `<body>`, so `<use href="#id">` works for a sprite on another origin. It
 * puts the same node back when a router swaps `<body>`. The core's validation is the primary
 * control; this cleanup is the second line in case a bad sprite gets through it: it drops every
 * element outside the SVG namespace, scripts, foreign objects, styles, links and animations of
 * a link or a handler, and every attribute that runs script or loads a URL from outside the
 * sprite. Checked in Chromium, Firefox and WebKit by spikes/TSK-067-cross-origin-inject.
 */
export const emitLoader = (spriteUrl: string, integrity: string): string =>
  '// Generated by svgworm. Do not edit.\n' +
  `(()=>{const u=${JSON.stringify(spriteUrl)},i=${JSON.stringify(integrity)},` +
  'N="http://www.w3.org/2000/svg",q=\'svg[data-svgworm="\'+i+\'"]\',' +
  'D=/^(script|foreignobject|style|a|handler|listener)$/i,' +
  'R=/^data:image\\/(png|jpe?g|gif|webp|avif)[;,]/i,' +
  // Browsers skip whitespace and control characters inside a URL scheme.
  'z=v=>v.replace(/[\\s\\u0000-\\u001f]/g,"");' +
  'if(document.querySelector(q))return;' +
  'fetch(u,{mode:"cors",credentials:"omit",integrity:i})' +
  '.then(r=>{if(!r.ok)throw Error("HTTP "+r.status);return r.text()})' +
  '.then(t=>{if(document.querySelector(q))return;' +
  'const d=new DOMParser().parseFromString(t,"image/svg+xml"),s=d.documentElement;' +
  'if(s.namespaceURI!==N||s.localName!=="svg"||d.getElementsByTagName("parsererror").length)throw Error("not an SVG");' +
  'for(const e of [...s.querySelectorAll("*")]){' +
  'const a=(e.getAttribute("attributeName")||"").trim();' +
  'if(e.namespaceURI!==N||D.test(e.localName)||(/^(set|animate)$/i.test(e.localName)&&/^(xlink:)?href$|^on/i.test(a)))e.remove()}' +
  'for(const e of [s,...s.querySelectorAll("*")])for(const a of [...e.attributes]){' +
  'const v=z(a.value),n=a.localName.toLowerCase(),h=n==="href";' +
  'if(/^on/.test(n)||/^(javascript|vbscript):/i.test(v)||/^(src|srcdoc|data|action|formaction|poster)$/.test(n)' +
  '||(h&&v[0]!=="#"&&!(e.localName==="image"&&R.test(v)))||/url\\((?!["\']?#)/i.test(v))e.removeAttributeNode(a)}' +
  's.setAttribute("data-svgworm",i);s.setAttribute("aria-hidden","true");' +
  's.setAttribute("width","0");s.setAttribute("height","0");' +
  'const n=document.importNode(s,true);' +
  // CSSOM, not a style attribute, so a strict style-src-attr policy cannot unhide the sprite.
  'n.style.cssText="position:absolute;width:0;height:0;overflow:hidden";' +
  'const p=()=>{if(document.body&&!n.isConnected)document.body.prepend(n)};' +
  'if(document.body)p();else document.addEventListener("DOMContentLoaded",p,{once:true});' +
  'new MutationObserver(p).observe(document.documentElement,{childList:true})})' +
  '.catch(e=>console.error("svgworm: sprite not loaded from "+u+": "+e.message))})();\n';
