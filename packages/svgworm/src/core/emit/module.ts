import type { CrossOrigin } from '../config/schema.ts';

import { serializeManifest, type ManifestInput } from './manifest.ts';

const HEADER = '// Generated by svgworm. Do not edit.';

export const emitManifestJson = (input: ManifestInput): string =>
  `${serializeManifest(input)}\n`;

export const emitModule = (input: ManifestInput): string =>
  `${HEADER}\nexport const manifest = ${serializeManifest(input)};\n`;

const TYPES_BODY = `export interface SvgwormFile {
  readonly file: string;
  readonly url: string;
}

export interface SvgwormIcon {
  readonly sprite: string;
  readonly id: string;
  readonly viewBox: string;
  readonly color: 'mono' | 'multicolor';
  readonly delivery: 'use' | 'img' | 'mask';
}

export interface SvgwormManifest<Name extends string> {
  readonly version: 1;
  readonly sprites: Readonly<Record<string, { readonly sprite: SvgwormFile | null; readonly stack: SvgwormFile | null }>>;
  readonly icons: Readonly<Record<Name, SvgwormIcon>>;
}

export declare const manifest: SvgwormManifest<IconName>;
`;

const INJECT_TYPES_BODY = `export interface SvgwormFile {
  readonly file: string;
  readonly url: string;
}

export interface SvgwormIntegrityFile extends SvgwormFile {
  readonly integrity: string;
}

export interface SvgwormIcon {
  readonly sprite: string;
  readonly id: string;
  readonly viewBox: string;
  readonly color: 'mono' | 'multicolor';
  readonly delivery: 'use' | 'img' | 'mask';
}

export interface SvgwormManifest<Name extends string> {
  readonly version: 2;
  readonly crossOrigin: 'inject';
  readonly sprites: Readonly<Record<string, { readonly sprite: SvgwormIntegrityFile | null; readonly stack: SvgwormFile | null; readonly loader: SvgwormIntegrityFile | null }>>;
  readonly icons: Readonly<Record<Name, SvgwormIcon>>;
}

export declare const manifest: SvgwormManifest<IconName>;
`;

export const emitTypes = (
  names: readonly string[],
  options: { readonly crossOrigin?: CrossOrigin | undefined } = {},
): string =>
  `${HEADER}\nexport type IconName =\n${names
    .map((name) => `  | ${JSON.stringify(name)}`)
    .join(
      '\n',
    )};\n\n${options.crossOrigin === 'inject' ? INJECT_TYPES_BODY : TYPES_BODY}`;
